import { chromium } from 'playwright'
import { resolve } from 'node:path'
const file = 'file://' + resolve(process.argv[2] ?? 'Аква пати — CRM.html')
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const errs = []
p.on('pageerror', e => errs.push(e.message))
p.on('requestfailed', r => errs.push('request failed: ' + r.url().slice(0,80)))
await p.goto(file, { waitUntil: 'load' })
await p.waitForTimeout(900)
console.log('Экран входа:', await p.getByText('Введите PIN').isVisible())
for (const d of '1111') await p.getByRole('button', { name: d, exact: true }).click()
await p.waitForTimeout(500)
await p.locator('.field-col', { hasText: 'Администратор' }).locator('select').selectOption('Смирнова Е. В.'); await p.waitForTimeout(150)
await p.getByRole('button', { name: 'Открыть смену' }).click()
await p.waitForTimeout(500)
// После открытия смены попадаем на «Заказы» (замечание 8).
console.log('После открытия смены:', p.url().split('#')[1])
await p.getByRole('link', { name: /Главное/ }).click(); await p.waitForTimeout(400)
console.log('Выручка за смену:', (await p.locator('.stat-value').first().textContent()))
await p.getByRole('link', { name: /Заказы/ }).click()
await p.waitForTimeout(400)
console.log('Строк в заказах:', await p.locator('.tbl tbody tr').count())
await p.locator('.tbl tbody tr', { hasText: '№ 4810' }).first().click()
await p.waitForTimeout(400)
console.log('Остаток по 4810:', (await p.locator('.modal-aside .card-total > span:last-child').first().textContent()))
console.log('URL:', p.url().split('/').pop())
await p.screenshot({ path: process.argv[3] ?? 'standalone.png' })
await b.close()
console.log(errs.length ? 'ОШИБКИ: ' + errs.slice(0,5).join(' | ') : 'Ошибок нет.')
